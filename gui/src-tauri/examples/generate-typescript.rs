use std::path::PathBuf;

use cortex_gui::{DashboardSnapshot, ParameterView};
use cortex_rs::ParameterInput;
use cortex_rs::nano::{NanoAmpControl, NanoBypassTarget, NanoFxSlot};
use ts_rs::TS;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let output = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/shared/ipc/generated");

    if output.exists() {
        std::fs::remove_dir_all(&output)?;
    }
    std::fs::create_dir_all(&output)?;

    DashboardSnapshot::export_all_to(&output)?;
    ParameterView::export_all_to(&output)?;
    ParameterInput::export_all_to(&output)?;
    NanoAmpControl::export_all_to(&output)?;
    NanoBypassTarget::export_all_to(&output)?;
    NanoFxSlot::export_all_to(&output)?;

    let mut bindings = Vec::new();
    for entry in std::fs::read_dir(&output)? {
        let path = entry?.path();
        if path.extension().is_some_and(|extension| extension == "ts") {
            let Some(binding) = path.file_stem().and_then(|stem| stem.to_str()) else {
                return Err("generated binding filename is not valid UTF-8".into());
            };
            bindings.push(binding.to_owned());

            let source = std::fs::read_to_string(&path)?;
            let mut normalized = source
                .lines()
                .map(str::trim_end)
                .collect::<Vec<_>>()
                .join("\n");
            normalized.push('\n');
            std::fs::write(path, normalized)?;
        }
    }
    bindings.sort_unstable();

    let mut index = String::from(
        "// This file was generated by cortex-gui's TypeScript binding generator. Do not edit this file manually.\n",
    );
    for binding in bindings {
        index.push_str(&format!(
            "export type {{ {binding} }} from \"./{binding}\";\n"
        ));
    }
    std::fs::write(output.join("index.ts"), index)?;

    Ok(())
}
